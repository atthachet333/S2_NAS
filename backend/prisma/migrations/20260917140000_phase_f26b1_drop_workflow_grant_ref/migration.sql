-- F26-B1: คำขอความร่วมมือเลิกเขียนทับแถวสิทธิ์ จึงไม่มีสิทธิ์ให้ชี้กลับไปหาอีกแล้ว
--
-- เดิมคำขอสร้างแถว ResourceAccess ให้ผู้รับงาน ซึ่งเขียนทับสิทธิ์ที่ผู้ดูแลเคยมอบด้วยมือ
-- ทิ้งอย่างเงียบ ๆ ตอนนี้คำขอเป็น "ชั้นทับ" ที่ถือเงื่อนไขของตัวเองและถูกนำไปรวมตอนอ่าน
-- สิทธิ์ที่มอบด้วยมือจึงไม่ถูกแตะต้องเลย และคอลัมน์นี้ไม่มีความหมายอีกต่อไป
--
-- **นี่เป็นคำสั่งแบบทำลายเพียงคำสั่งเดียวของเฟสนี้ และปลอดภัยด้วยเหตุผลที่ตรวจสอบแล้ว:**
--   - ตาราง external_workflow_requests เพิ่งถูกสร้างใน 20260917110000 ซึ่งยังไม่ commit
--     และยังไม่เคยออกสู่การใช้งานจริง
--   - ตรวจก่อนแล้ว: มี 0 แถวในระบบจริง และ 0 แถวที่คอลัมน์นี้ไม่เป็น null
--   - ไม่มีข้อมูลของผู้ใช้คนใดอยู่ในคอลัมน์นี้ จึงไม่มีอะไรสูญหาย
--
-- การปล่อยคอลัมน์ที่ไม่มีใครเขียนและไม่มีใครอ่านทิ้งไว้ อันตรายกว่าในระยะยาว - มันชวนให้
-- คนอ่านโค้ดในอนาคตเข้าใจว่าคำขอยังผูกกับแถวสิทธิ์อยู่ ซึ่งตรงข้ามกับความจริง
