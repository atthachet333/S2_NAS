/**
 * การปรับข้อความให้เทียบกันได้ก่อนค้นหา
 *
 * ภาษาไทยไม่มีช่องว่างระหว่างคำ การตัดคำจึงใช้ไม่ได้กับที่นี่
 * การค้นหาของระบบนี้เป็นการหา "ข้อความย่อยที่ตรงกัน" ไม่ใช่การหาคำที่ถูกตัดไว้แล้ว
 * ดังนั้นสิ่งที่ต้องทำคือทำให้ทั้งคำค้นและเนื้อหาอยู่ในรูปแบบเดียวกันเสมอ
 *
 * สิ่งที่ทำ:
 *   - NFC เพื่อให้สระและวรรณยุกต์ที่เขียนแยกกับที่รวมกันอยู่แล้วเทียบกันได้
 *   - ตัวพิมพ์เล็กสำหรับภาษาอังกฤษ (ภาษาไทยไม่มีตัวพิมพ์ จึงไม่ถูกกระทบ)
 *   - ยุบช่องว่างทุกชนิดให้เหลือช่องเดียว รวมถึงขึ้นบรรทัดใหม่และแท็บ
 *
 * สิ่งที่ห้ามทำ:
 *   - ห้ามตัดอักขระที่ไม่ใช่ ASCII ทิ้ง - นั่นจะลบภาษาไทยทั้งหมด
 *   - ห้ามลบวรรณยุกต์หรือสระ - "ภาษี" กับ "ภาษ" ไม่ใช่คำเดียวกัน
 */

/** อักขระควบคุมที่ไม่ควรอยู่ในข้อความค้นหา ยกเว้นที่เป็นช่องว่างอยู่แล้ว */
const CONTROL_EXCEPT_WHITESPACE = /[\p{Cc}\p{Cf}]/gu;

/** ทำความสะอาดข้อความดิบที่สกัดมา ก่อนเก็บเป็น extractedText */
export function cleanExtractedText(raw: string): string {
  return raw
    .normalize('NFC')
    // ยุบช่องว่างซ้ำ ๆ แต่คงการขึ้นบรรทัดไว้หนึ่งชั้น เพื่อให้ตัดข้อความมาแสดงแล้วยังอ่านรู้เรื่อง
    .replace(/\r\n?/g, '\n')
    .replace(/[^\S\n]+/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .replace(CONTROL_EXCEPT_WHITESPACE, '')
    .trim();
}

/** รูปแบบที่ใช้เป็นเป้าของการค้นหา - ทั้งเนื้อหาและคำค้นต้องผ่านฟังก์ชันเดียวกันนี้ */
export function normalizeForSearch(value: string): string {
  return value
    .normalize('NFC')
    .toLocaleLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * ตัดข้อความให้ไม่เกินเพดาน
 *
 * คืน truncated = true เมื่อถูกตัดจริง เพื่อให้บอกผู้ใช้ได้ตามจริงว่าเอกสารนี้
 * ถูกทำดัชนีไม่ครบ ไม่ใช่ทำเหมือนว่าค้นได้ทั้งฉบับแล้วเงียบ ๆ
 */
export function truncateText(value: string, maxChars: number): { text: string; truncated: boolean } {
  if (value.length <= maxChars) return { text: value, truncated: false };
  return { text: value.slice(0, maxChars), truncated: true };
}
