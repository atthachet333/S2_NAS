/**
 * การปรับข้อความให้เทียบกันได้ก่อนค้นหา
 *
 * ภาษาไทยไม่มีช่องว่างระหว่างคำ การตัดคำจึงใช้ไม่ได้กับที่นี่
 * การค้นหาของระบบนี้เป็นการหา "ข้อความย่อยที่ตรงกัน" ไม่ใช่การหาคำที่ถูกตัดไว้แล้ว
 * ดังนั้นสิ่งที่ต้องทำคือทำให้ทั้งคำค้นและเนื้อหาอยู่ในรูปแบบเดียวกันเสมอ
 *
 * สิ่งที่ทำ:
 *   - NFC เพื่อให้สระและวรรณยุกต์ที่เขียนแยกกับที่รวมกันอยู่แล้วเทียบกันได้
 *   - ตัวพิมพ์เล็กสำหรับภาษาอังกฤษ (ภาษาไทยไม่มีตัวพิมพ์ จึงไม่ถูกกระทบ)
 *   - ยุบช่องว่างทุกชนิดให้เหลือช่องเดียว รวมถึงขึ้นบรรทัดใหม่และแท็บ
 *
 * สิ่งที่ห้ามทำ:
 *   - ห้ามตัดอักขระที่ไม่ใช่ ASCII ทิ้ง - นั่นจะลบภาษาไทยทั้งหมด
 *   - ห้ามลบวรรณยุกต์หรือสระ - "ภาษี" กับ "ภาษ" ไม่ใช่คำเดียวกัน
 */

/** อักขระควบคุมที่ไม่ควรอยู่ในข้อความค้นหา ยกเว้นที่เป็นช่องว่างอยู่แล้ว */
const CONTROL_EXCEPT_WHITESPACE = /[\p{Cc}\p{Cf}]/gu;

/** ทำความสะอาดข้อความดิบที่สกัดมา ก่อนเก็บเป็น extractedText */
export function cleanExtractedText(raw: string): string {
  return raw
    .normalize('NFC')
    // ยุบช่องว่างซ้ำ ๆ แต่คงการขึ้นบรรทัดไว้หนึ่งชั้น เพื่อให้ตัดข้อความมาแสดงแล้วยังอ่านรู้เรื่อง
    .replace(/\r\n?/g, '\n')
    .replace(/[^\S\n]+/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .replace(CONTROL_EXCEPT_WHITESPACE, '')
    .trim();
}

/**
 * ช่วงอักขระไทยใน Unicode
 * ใช้ตัดสินว่าช่องว่างที่พบอยู่ "ระหว่างตัวอักษรไทยสองตัว" หรือไม่
 */
const THAI = '\\u0E00-\\u0E7F';
const SPACE_BETWEEN_THAI = new RegExp(`([${THAI}]) +(?=[${THAI}])`, 'g');

/**
 * ประกอบสระอำที่ถูกแยกออกเป็นสองตัวกลับคืน
 *
 * นิคหิต (U+0E4D) ตามด้วยสระอา (U+0E32) คือสระอำ (U+0E33) ที่ถูกเขียนแยก
 * ยูนิโคดไม่ได้กำหนดการประกอบคู่นี้ไว้ใน NFC ภาษาไทยจึงต้องจัดการเอง
 *
 * เครื่องมือ OCR แยกสองตัวนี้ออกจากกันเป็นปกติ ถ้าไม่ประกอบกลับ
 * คำว่า "กำ" ที่อ่านได้จะไม่มีวันตรงกับ "กำ" ที่ผู้ใช้พิมพ์ แม้จะเป็นคำเดียวกัน
 *
 * วรรณยุกต์ที่คั่นอยู่ตรงกลางถูกคงลำดับไว้ตามเดิม
 */
function recomposeSaraAm(value: string): string {
  return value
    .replace(/\u0E4D\u0E32/g, '\u0E33')
    .replace(/([\u0E48-\u0E4B])\u0E4D\u0E32/g, '\u0E33$1');
}

/**
 * รูปแบบที่ใช้เป็นเป้าของการค้นหา - ทั้งเนื้อหาและคำค้นต้องผ่านฟังก์ชันเดียวกันนี้
 *
 * การที่ทั้งสองฝั่งผ่านฟังก์ชันเดียวกันคือหัวใจ: ไม่ว่าจะปรับรูปแบบอย่างไร
 * ข้อความที่เก็บไว้กับคำที่ผู้ใช้พิมพ์จะมาบรรจบกันที่รูปแบบเดียวเสมอ
 *
 * ขั้นตอนเฉพาะของภาษาไทยสองข้อ:
 *
 *   1. ตัดช่องว่างที่อยู่ระหว่างตัวอักษรไทยสองตัวทิ้ง
 *      ภาษาไทยไม่เขียนเว้นวรรคระหว่างตัวอักษรในคำเดียวกัน ช่องว่างแบบนั้น
 *      จึงไม่ใช่ความตั้งใจของผู้เขียน แต่เป็นผลข้างเคียงของการอ่านภาพ
 *      (เครื่องมือ OCR แยก "กำกับ" ออกเป็น "ก ํ า ก ั บ" เป็นปกติ)
 *      ช่องว่างระหว่างไทยกับอังกฤษยังคงอยู่ เพราะที่นั่นเป็นการเว้นวรรคจริง
 *
 *   2. ประกอบสระอำกลับคืน
 *
 * ราคาที่ต้องจ่ายอย่างตรงไปตรงมา: การเว้นวรรคระหว่างวลีไทยก็ถูกตัดไปด้วย
 * "ภาษี ดี" กับ "ภาษีดี" จึงกลายเป็นข้อความเดียวกันในสายตาของการค้นหา
 * ความแม่นยำลดลงเล็กน้อยแลกกับการที่ข้อความจาก OCR ค้นหาได้จริง
 * ซึ่งคุ้มค่า เพราะการค้นหาภาษาไทยเป็นการหาข้อความย่อยอยู่แล้วตั้งแต่ต้น
 */
export function normalizeForSearch(value: string): string {
  const collapsed = value
    .normalize('NFC')
    .toLocaleLowerCase()
    .replace(/\s+/g, ' ')
    .trim();

  // วนซ้ำเพราะช่องว่างที่อยู่ติดกันหลายช่วงต้องถูกตัดทีละชั้น
  let result = collapsed;
  for (let pass = 0; pass < 8; pass += 1) {
    const next = result.replace(SPACE_BETWEEN_THAI, '$1');
    if (next === result) break;
    result = next;
  }

  return recomposeSaraAm(result);
}

/**
 * ตัดข้อความให้ไม่เกินเพดาน
 *
 * คืน truncated = true เมื่อถูกตัดจริง เพื่อให้บอกผู้ใช้ได้ตามจริงว่าเอกสารนี้
 * ถูกทำดัชนีไม่ครบ ไม่ใช่ทำเหมือนว่าค้นได้ทั้งฉบับแล้วเงียบ ๆ
 */
export function truncateText(value: string, maxChars: number): { text: string; truncated: boolean } {
  if (value.length <= maxChars) return { text: value, truncated: false };
  return { text: value.slice(0, maxChars), truncated: true };
}
