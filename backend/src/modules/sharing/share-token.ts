import { createHash, randomBytes, timingSafeEqual } from 'node:crypto';

/**
 * โทเคนของลิงก์แชร์ภายนอก (F18)
 *
 * โทเคนคือสิ่งเดียวที่กั้นระหว่างเอกสารกับอินเทอร์เน็ต ใครถือก็เข้าได้
 * จึงต้องเดาไม่ได้ และต้องไม่มีอยู่ในฐานข้อมูลในรูปที่ใช้งานได้
 */

/**
 * 32 ไบต์ = 256 บิต
 *
 * มากกว่าเกณฑ์ขั้นต่ำ 128 บิตเท่าตัว เพราะโทเคนนี้ไม่มีชั้นป้องกันอื่นรองรับ
 * ไม่มีชื่อผู้ใช้ ไม่มีการล็อกบัญชี ไม่มีอะไรให้ผู้โจมตีต้องผ่านก่อน
 * ต้นทุนของบิตที่เพิ่มมาคือความยาว URL อีกไม่กี่ตัวอักษร ซึ่งถูกกว่ามาก
 */
const TOKEN_BYTES = 32;

/**
 * สร้างโทเคนใหม่ - ค่าที่คืนมาจะไม่มีวันถูกเก็บลงฐานข้อมูล
 *
 * base64url เพราะปลอดภัยใน URL โดยไม่ต้องเข้ารหัสซ้ำ และสั้นกว่า hex ราวหนึ่งในสาม
 */
export function generateShareToken(): string {
  return randomBytes(TOKEN_BYTES).toString('base64url');
}

/**
 * แฮชของโทเคนสำหรับเก็บและค้นหา
 *
 * ใช้ SHA-256 ธรรมดา ไม่ใช้ bcrypt/argon2 อย่างที่ใช้กับรหัสผ่าน - และนั่นถูกต้อง
 *
 * ฟังก์ชันแฮชรหัสผ่านออกแบบมาให้ "ช้า" เพื่อสู้กับการเดารหัสที่มนุษย์ตั้ง
 * ซึ่งมีเอนโทรปีต่ำมาก แต่โทเคนนี้สุ่มมา 256 บิต การไล่เดาไม่มีทางสำเร็จ
 * ไม่ว่าแฮชจะเร็วแค่ไหน ในทางกลับกัน แฮชที่ช้าจะบังคับให้ต้องสแกนทั้งตาราง
 * เพราะ bcrypt ให้ค่าต่างกันทุกครั้ง ค้นหาด้วยดัชนีไม่ได้
 */
export function hashShareToken(token: string): string {
  return createHash('sha256').update(token, 'utf8').digest('hex');
}

/**
 * เทียบค่าลับแบบไม่ให้เวลาที่ใช้บอกใบ้
 *
 * การเทียบสตริงตามปกติจะหยุดที่ตัวอักษรแรกที่ต่างกัน ผู้โจมตีที่วัดเวลาได้ละเอียดพอ
 * จึงค่อย ๆ ไล่หาค่าที่ถูกได้ทีละตัวอักษร แทนที่จะต้องเดาทั้งก้อนพร้อมกัน
 */
export function safeEqual(a: string, b: string): boolean {
  const left = Buffer.from(a, 'utf8');
  const right = Buffer.from(b, 'utf8');
  // ความยาวต่างกันคือคำตอบอยู่แล้ว และ timingSafeEqual ต้องการบัฟเฟอร์ขนาดเท่ากัน
  if (left.length !== right.length) return false;
  return timingSafeEqual(left, right);
}

/** URL ที่ส่งให้ผู้รับ - ปรากฏครั้งเดียวตอนสร้าง ไม่มีเส้นทางใดสร้างซ้ำได้ */
export function shareUrl(baseUrl: string, token: string): string {
  return `${baseUrl.replace(/\/+$/, '')}/s/${token}`;
}
